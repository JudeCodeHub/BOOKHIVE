// Generates src/lib/api-schema.d.ts (TypeScript types) from the backend's OpenAPI spec.
//
//   pnpm api:types          (the backend must be running: cd backend && ./gradlew bootRun)
//
// Re-run it whenever a backend endpoint or DTO changes, and commit the result: if a field
// is renamed in Java, the frontend then shows a type error instead of breaking at runtime.
//
// OPENAPI_URL  spec location (default http://localhost:8080/v3/api-docs)
// OPENAPI_AUTH "user:password" for HTTP Basic auth, if the spec is behind a login. Not needed
//              locally: the dev profile serves the docs publicly.

import { writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const url = process.env.OPENAPI_URL ?? "http://localhost:8080/v3/api-docs";
const output = new URL("../src/lib/api-schema.d.ts", import.meta.url);

const headers = { Accept: "application/json" };
if (process.env.OPENAPI_AUTH) {
  headers.Authorization = `Basic ${Buffer.from(process.env.OPENAPI_AUTH).toString("base64")}`;
}

let spec;
try {
  const response = await fetch(url, { headers });
  if (!response.ok) {
    throw new Error(
      `HTTP ${response.status}${response.status === 401 ? " (set OPENAPI_AUTH)" : ""}`,
    );
  }
  spec = await response.json();
} catch (error) {
  console.error(`Could not load the OpenAPI spec from ${url}: ${error.message}`);
  console.error("Is the backend running? (cd backend && ./gradlew bootRun)");
  process.exit(1);
}

const ast = await openapiTS(spec);
const banner = `// Generated by scripts/generate-api-types.mjs from ${url}. Do not edit by hand.\n\n`;
await writeFile(output, banner + astToString(ast));
console.log(`Wrote ${output.pathname} (${Object.keys(spec.paths ?? {}).length} paths)`);
